
"""
Module 03: Text Embedding Generation

Project: RAG_Own_Decision_Making_System

Responsibilities:
1. Load chunks generated by Module 02.
2. Load a pretrained Sentence Transformer model.
3. Convert text chunks into numerical embeddings.
4. Generate embeddings in batches.
5. Normalize embedding vectors.
6. Preserve chunk IDs and metadata.
7. Save embeddings into JSONL format.
"""

import json
import logging

from pathlib import Path
from typing import Optional

import numpy as np
import torch

from sentence_transformers import SentenceTransformer
from tqdm import tqdm


# ==========================================================
# 1. PROJECT CONFIGURATION
# ==========================================================

PROJECT_ROOT = Path(__file__).resolve().parent.parent

INPUT_FILE = (
    PROJECT_ROOT
    / "data"
    / "processed"
    / "chunks.jsonl"
)

OUTPUT_FILE = (
    PROJECT_ROOT
    / "data"
    / "processed"
    / "embeddings.jsonl"
)


# ==========================================================
# 2. LOGGING CONFIGURATION
# ==========================================================

logging.basicConfig(
    level=logging.INFO,
    format="%(levelname)s: %(message)s"
)

logger = logging.getLogger(__name__)


# ==========================================================
# 3. EMBEDDING GENERATOR CLASS
# ==========================================================

class EmbeddingGenerator:
    """
    Generates numerical embeddings for text chunks
    using Sentence Transformers.
    """

    def __init__(
        self,
        input_file: Path = INPUT_FILE,
        output_file: Path = OUTPUT_FILE,
        model_name: str = "sentence-transformers/all-MiniLM-L6-v2",
        batch_size: int = 32,
        normalize_embeddings: bool = True,
        device: Optional[str] = None
    ):

        self.input_file = Path(input_file)
        self.output_file = Path(output_file)

        self.model_name = model_name

        self.batch_size = batch_size

        self.normalize_embeddings = normalize_embeddings

        if self.batch_size <= 0:
            raise ValueError("Batch size must be positive.")

        # Automatically select available hardware
        if device is None:

            if torch.cuda.is_available():
                self.device = "cuda"

            elif (
                hasattr(torch.backends, "mps")
                and torch.backends.mps.is_available()
            ):
                self.device = "mps"

            else:
                self.device = "cpu"

        else:
            self.device = device

        self.documents = []
        self.embeddings = []

        self.model = None

        self.embedding_dimension = None

        logger.info("Embedding Generator Initialized")

        logger.info(f"Model: {self.model_name}")

        logger.info(f"Device: {self.device}")

        logger.info(f"Batch Size: {self.batch_size}")


    # ======================================================
    # 4. LOAD CHUNKS FROM MODULE 02
    # ======================================================

    def load_chunks(self) -> list[dict]:
        """
        Read generated chunks from chunks.jsonl.
        """

        if not self.input_file.exists():

            raise FileNotFoundError(
                f"Chunk file not found: {self.input_file}"
            )

        self.documents = []

        with self.input_file.open(
            "r",
            encoding="utf-8"
        ) as file:

            for line_number, line in enumerate(
                file,
                start=1
            ):

                if not line.strip():
                    continue

                try:

                    document = json.loads(line)

                    if not isinstance(document.get("text"), str):
                        logger.warning(
                            f"Invalid text at line {line_number}"
                        )
                        continue

                    if not document["text"].strip():
                        continue

                    if not document.get("chunk_id"):
                        logger.warning(
                            f"Missing chunk ID at line {line_number}"
                        )
                        continue

                    self.documents.append(document)

                except json.JSONDecodeError as error:

                    logger.warning(
                        f"Invalid JSON at line {line_number}: {error}"
                    )

        logger.info(
            f"Successfully loaded {len(self.documents)} chunks."
        )

        return self.documents


    # ======================================================
    # 5. LOAD PRETRAINED EMBEDDING MODEL
    # ======================================================

    def load_model(self) -> None:
        """
        Load Sentence Transformer embedding model.
        """

        logger.info("Loading embedding model...")

        self.model = SentenceTransformer(
            self.model_name,
            device=self.device
        )

        self.embedding_dimension = (
            self.model.get_sentence_embedding_dimension()
        )

        logger.info("Embedding model loaded successfully.")

        logger.info(
            f"Embedding Dimension: {self.embedding_dimension}"
        )


    # ======================================================
    # 6. GENERATE EMBEDDINGS
    # ======================================================

    def generate_embeddings(self) -> list[dict]:
        """
        Convert text chunks into numerical vectors.

        Embeddings are generated in batches to
        reduce memory consumption.
        """

        if self.model is None:

            raise RuntimeError(
                "Embedding model is not loaded. "
                "Call load_model() first."
            )

        if not self.documents:

            logger.warning("No chunks available for embedding.")

            return []

        self.embeddings = []

        # Extract text from each chunk
        texts = [
            document["text"]
            for document in self.documents
        ]

        logger.info(
            f"Generating embeddings for {len(texts)} chunks..."
        )

        # Process text in batches
        for start in tqdm(
            range(0, len(texts), self.batch_size),
            desc="Generating Embeddings"
        ):

            end = start + self.batch_size

            batch_texts = texts[start:end]

            # Generate numerical vectors
            batch_embeddings = self.model.encode(
                batch_texts,
                batch_size=self.batch_size,
                convert_to_numpy=True,
                normalize_embeddings=self.normalize_embeddings,
                show_progress_bar=False
            )

            # Validate numerical output
            if not np.isfinite(batch_embeddings).all():

                raise ValueError(
                    f"Invalid embedding values in batch "
                    f"starting at index {start}"
                )

            # Connect embeddings with their original chunks
            for offset, embedding in enumerate(batch_embeddings):

                original_document = self.documents[start + offset]

                embedding_record = {

                    "chunk_id": original_document["chunk_id"],

                    "text": original_document["text"],

                    "embedding": embedding.astype(
                        np.float32
                    ).tolist(),

                    "metadata": original_document.get(
                        "metadata",
                        {}
                    )
                }

                self.embeddings.append(embedding_record)

        logger.info(
            f"Generated {len(self.embeddings)} embeddings."
        )

        return self.embeddings


    # ======================================================
    # 7. SAVE EMBEDDINGS
    # ======================================================

    def save_embeddings(self) -> None:
        """
        Save embeddings, text, IDs and metadata
        into JSONL format.
        """

        if not self.embeddings:

            logger.warning(
                "No embeddings available to save."
            )

            return

        self.output_file.parent.mkdir(
            parents=True,
            exist_ok=True
        )

        with self.output_file.open(
            "w",
            encoding="utf-8"
        ) as file:

            for record in self.embeddings:

                file.write(
                    json.dumps(
                        record,
                        ensure_ascii=False
                    ) + "\n"
                )

        logger.info(
            f"Embeddings saved successfully: {self.output_file}"
        )


    # ======================================================
    # 8. CALCULATE SIMILARITY
    # ======================================================

    def calculate_similarity(
        self,
        text_one: str,
        text_two: str
    ) -> float:
        """
        Calculate cosine similarity between two texts.

        Higher scores indicate greater semantic similarity.
        """

        if self.model is None:

            raise RuntimeError(
                "Load the model before calculating similarity."
            )

        vectors = self.model.encode(
            [text_one, text_two],
            convert_to_numpy=True,
            normalize_embeddings=True
        )

        similarity = np.dot(
            vectors[0],
            vectors[1]
        )

        return float(similarity)


    # ======================================================
    # 9. DISPLAY EMBEDDING SUMMARY
    # ======================================================

    def display_summary(self) -> None:
        """
        Display embedding generation statistics.
        """

        total_embeddings = len(self.embeddings)

        print("\n" + "=" * 55)

        print("          EMBEDDING GENERATION SUMMARY")

        print("=" * 55)

        print(f"Input Chunks       : {len(self.documents)}")

        print(f"Generated Vectors  : {total_embeddings}")

        print(f"Embedding Model    : {self.model_name}")

        print(f"Vector Dimensions  : {self.embedding_dimension}")

        print(f"Batch Size         : {self.batch_size}")

        print(f"Device             : {self.device}")

        print(
            f"Normalized         : {self.normalize_embeddings}"
        )

        print(f"Output File        : {self.output_file}")

        print("=" * 55)


# ==========================================================
# 10. MAIN EXECUTION
# ==========================================================

def main():

    # Initialize embedding generator
    generator = EmbeddingGenerator(

        model_name="sentence-transformers/all-MiniLM-L6-v2",

        batch_size=32,

        normalize_embeddings=True
    )

    # Step 1: Load chunks from Module 02
    generator.load_chunks()

    # Step 2: Load pretrained embedding model
    generator.load_model()

    # Step 3: Generate numerical vectors
    generator.generate_embeddings()

    # Step 4: Save embeddings
    generator.save_embeddings()

    # Step 5: Display summary
    generator.display_summary()


# Execute the module
if __name__ == "__main__":

    main()
